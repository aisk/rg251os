#!/usr/bin/env python3
"""
Generate app/frontend/romdb_data.c, the GBA ROM database of the frontend
(see romdb.h), from two libretro-database DAT files:

  metadat/no-intro/Nintendo - Game Boy Advance.dat     names, CRC32,
                                                       size, serial
  metadat/releaseyear/Nintendo - Game Boy Advance.dat  release year by CRC

Run through `make romdb` (mk/romdb.mk downloads the files at the pinned
commit and checks their hashes):

  romdb-gen.py COMMIT NO_INTRO_DAT RELEASEYEAR_DAT > romdb_data.c

Per entry: the No-Intro name, CRC32 and size of the ROM, the 4 character
game code from the serial field (the code in the cartridge header at
0xAC), the software version derived from "(Rev N)" in the name (the
header byte at 0xBC; no "Rev" is version 0) and a year:

  year     the first release year of the title: the earliest year of
           this entry and of every entry with the same title (the name up
           to " (") or, except for prototypes, betas, demos and samples,
           the same first three letters of the game code (the same game
           in other regions). So a 2005 US release of a 2004 Japanese game
           gets 2004, and a re-release (Virtual Console, collections)
           without a year of its own gets the original's.
  flag     YEAR_INHERITED in the entry when that year is not the entry's
           own release year in releaseyear.dat (or it has none).

Entries are sorted by game code, version and name, so the frontend looks
codes up by binary search; entries without a game code (homebrew, cheat
devices, some prototypes) sort first and are only found by CRC.
"""
import re
import sys

NAME_LIMIT = 159  # romdb.h ROMDB_NAME_MAX - 1
NO_FAMILY_CODE = re.compile(r"\((Proto|Beta|Demo|Sample|Tech Demo)[ )0-9]")


def parse_no_intro(path):
    text = open(path, encoding="utf-8").read()
    entries = []
    for block in re.findall(r"^game \((.*?)^\)", text, re.S | re.M):
        name = re.search(r'^\tname "(.*)"$', block, re.M).group(1)
        for rom in re.findall(r"^\trom \( (.*) \)$", block, re.M):
            crc = int(re.search(r"\bcrc ([0-9A-Fa-f]{8})\b", rom).group(1), 16)
            size = int(re.search(r"\bsize (\d+)\b", rom).group(1))
            serial = re.search(r'\bserial "([^"]*)"', rom)
            code = serial.group(1)[:4] if serial else ""
            if not re.fullmatch(r"[A-Z0-9]{4}", code):
                code = ""
            rev = re.search(r"\(Rev (\d+)\)", name)
            entries.append({
                "name": name, "crc": crc, "size": size, "code": code,
                "version": int(rev.group(1)) if rev else 0,
            })
    return entries


def parse_years(path):
    text = open(path, encoding="utf-8").read()
    years = {}
    for year, crc in re.findall(
            r'releaseyear "(\d{4})"\s*rom \(\s*crc ([0-9A-Fa-f]{8})', text):
        years[int(crc, 16)] = int(year)
    return years


def c_string(s):
    out = s.replace("\\", "\\\\").replace('"', '\\"').replace("?", "\\?")
    if any(ord(c) < 32 or ord(c) > 126 for c in out):
        raise SystemExit("non-ASCII name: %r" % s)
    return out


def main():
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    commit, no_intro, release = sys.argv[1:]
    entries = parse_no_intro(no_intro)
    years = parse_years(release)

    def title(e):
        return e["name"].split(" (")[0]

    by_title, by_code3 = {}, {}
    for e in entries:
        y = years.get(e["crc"])
        e["own"] = y
        if not y:
            continue
        by_title.setdefault(title(e), []).append(y)
        if e["code"] and not NO_FAMILY_CODE.search(e["name"]):
            by_code3.setdefault(e["code"][:3], []).append(y)
    own = inherited = 0
    for e in entries:
        cand = list(by_title.get(title(e), []))
        if e["code"] and not NO_FAMILY_CODE.search(e["name"]):
            cand += by_code3.get(e["code"][:3], [])
        if e["own"]:
            cand.append(e["own"])
        e["year"] = min(cand) if cand else 0
        e["inherited"] = bool(e["year"]) and e["year"] != e["own"]
        own += bool(e["own"])
        inherited += e["inherited"]
        if e["year"] and not 2000 <= e["year"] <= 2127:
            raise SystemExit("year out of range: %r" % e)
        if len(e["name"]) > NAME_LIMIT:
            raise SystemExit("name too long: %r" % e["name"])
    entries.sort(key=lambda e: (e["code"], e["version"], e["name"], e["crc"]))

    w = sys.stdout.write
    w("/*\n * GBA ROM database, generated by mk/romdb-gen.py (make romdb).\n"
      " * Do not edit.\n *\n"
      " * Source: libretro-database, https://github.com/libretro/libretro-database\n"
      " * at commit %s:\n"
      " *   metadat/no-intro/Nintendo - Game Boy Advance.dat\n"
      " *   metadat/releaseyear/Nintendo - Game Boy Advance.dat\n"
      " * The names, CRCs, sizes and serials are No-Intro's (https://no-intro.org),\n"
      " * as distributed by libretro-database. libretro-database is licensed\n"
      " * under the Creative Commons Attribution-ShareAlike 4.0 International\n"
      " * license (CC BY-SA 4.0), and so is this adapted table.\n *\n"
      " * %d entries, %d with a game code, %d with their own release year,\n"
      " * %d with a year inherited from the same title or game (see the\n"
      " * generator), %d without a year.\n */\n"
      % (commit, len(entries), sum(1 for e in entries if e["code"]), own,
         inherited, sum(1 for e in entries if not e["year"])))
    w('#include "romdb.h"\n\nconst char romdb_names[] =\n')
    offset = 0
    for e in entries:
        e["offset"] = offset
        offset += len(e["name"]) + 1
        w('\t"%s\\0"\n' % c_string(e["name"]))
    w("\t;\n\nconst struct romdb_entry romdb_entries[] = {\n")
    for e in entries:
        flags = " | YEAR_INHERITED" if e["inherited"] else ""
        w('\t{ 0x%08x, %d, %d, "%s", %d, %d%s },\n'
          % (e["crc"], e["size"], e["offset"],
             e["code"], e["version"],
             e["year"] - 2000 if e["year"] else 0, flags))
    w("};\n\nconst int romdb_count = %d;\n" % len(entries))


if __name__ == "__main__":
    main()
